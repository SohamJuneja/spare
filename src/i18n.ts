export type Lang = 'en' | 'es'

const dictionaries: Record<Lang, Record<StringKey, string>> = { en, es }

export function pickLang(host: string | undefined): Lang {
  return host?.toLowerCase().startsWith('es') ? 'es' : 'en'
}

export const lang: Lang = pickLang(typeof window !== 'undefined' ? (getHostLanguage() ?? navigator.language) : 'en')

export function translate(l: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  return dictionaries[l][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

export const t = (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars)

/** Picks `${base}.one` or `${base}.other`. */
export function tn(base: string, n: number, vars: Record<string, string | number> = {}): string {
  return t(`${base}.${n === 1 ? 'one' : 'other'}` as StringKey, { n, ...vars })
}

